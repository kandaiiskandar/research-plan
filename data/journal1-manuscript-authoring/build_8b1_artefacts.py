def write_csv(name, fields, rows):
    path = os.path.join(OUT, name)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow(dict(zip(fields, r)))
    return path


def main():
    os.makedirs(OUT, exist_ok=True)
    p1 = write_csv("quantitative-provenance.csv", QUANT_FIELDS, QUANT)
    p2 = write_csv("claim-evidence-audit.csv", CLAIM_FIELDS, CLAIMS)

    # Parser test: csv.DictReader and pandas must both agree on row counts.
    result = {}
    import pandas as pd
    for path, expected, fields in ((p1, len(QUANT), QUANT_FIELDS),
                                   (p2, len(CLAIMS), CLAIM_FIELDS)):
        base = os.path.basename(path)
        with open(path, newline="", encoding="utf-8") as fh:
            rows = list(csv.DictReader(fh))
        df = pd.read_csv(path)
        result[base] = {
            "dictreader_rows": len(rows),
            "pandas_rows": int(df.shape[0]),
            "dictreader_fields": list(rows[0].keys()),
            "pandas_columns": list(df.columns),
            "expected_rows": expected,
            "fields_match": list(rows[0].keys()) == fields == list(df.columns),
            "row_counts_agree": len(rows) == int(df.shape[0]) == expected,
            "no_empty_required_cells": all(
                all(str(r[k]).strip() for k in fields) for r in rows),
        }
    with open(os.path.join(OUT, "parser-test.json"), "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2)
    print(json.dumps(result, indent=2))


